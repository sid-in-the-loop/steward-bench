#!/usr/bin/env python3
"""Generate clients from the interface description: tools/regenerate [--out TEMPLATE] NAME..."""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESCRIPTION = ROOT / "interface" / "telco-billing.api"
CONFIG = ROOT / "release.conf"


def read_output_template() -> str:
    for line in CONFIG.read_text().splitlines():
        if line.startswith("output="):
            return line.removeprefix("output=")
    sys.exit("regenerate: no output= in release.conf")


def parse(text: str) -> tuple[str, list[tuple[str, str, str, list[str]]]]:
    version = ""
    endpoints = []
    for line in text.splitlines():
        if line.startswith("version:"):
            version = line.removeprefix("version:").strip()
        elif line.startswith("endpoint:"):
            name, method, path, *scopes = line.removeprefix("endpoint:").split()
            endpoints.append((name, method, path, scopes))
    return version, endpoints


def render(client: str, version: str, endpoints: list[tuple[str, str, str, list[str]]]) -> str:
    out = [
        "# Generated by tools/regenerate from interface/telco-billing.api. Do not edit by hand.",
        f'API_VERSION = "{version}"',
        f'CLIENT = "{client}"',
        "",
        "",
        "def to_minor_units(amount):",
        "    return int(amount * 100)",
    ]
    for name, method, path, scopes in endpoints:
        if client not in scopes:
            continue
        args = ["msisdn"] if "{msisdn}" in path else []
        body = ""
        if name == "topup":
            args.append("amount")
            body = ', "body": {"amount_minor": to_minor_units(amount)}'
        out += ["", "", f"def {name}({', '.join(args)}):"]
        out.append(f'    return {{"method": "{method}", "path": f"{path}"{body}}}')
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", help="output folder template with {name}")
    parser.add_argument("names", nargs="+")
    args = parser.parse_args()
    template = args.out or read_output_template()
    version, endpoints = parse(DESCRIPTION.read_text())
    for name in args.names:
        target = ROOT / template.format(name=name)
        target.mkdir(parents=True, exist_ok=True)
        (target / "client.py").write_text(render(name, version, endpoints))
        print(f"generated {target.relative_to(ROOT)}/client.py at {version}")


if __name__ == "__main__":
    main()
PY
