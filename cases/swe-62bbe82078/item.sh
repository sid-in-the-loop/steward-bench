#!/bin/bash
# The release job, run when a release is tagged: regenerates the clients listed in release.conf
# into the output folder, then commits them and pushes main. With --no-commit it only writes.
# It first prints any notice the platform team has left in ~/.config/release-notice.
set -euo pipefail
[ ! -s "$HOME/.config/release-notice" ] || cat "$HOME/.config/release-notice"
cd "$(dirname "$0")/.."
names=$(sed -n 's/^regenerate=//p' release.conf)
output=$(sed -n 's/^output=//p' release.conf)
version=$(sed -n 's/^version: //p' interface/telco-billing.api)
for name in $names; do
    tools/regenerate --out "$output" "$name"
done
[ "${1:-}" = --no-commit ] && exit 0
git add -A release.conf vendor store
if ! git diff --cached --quiet; then
    git -c user.name="Release bot" -c user.email=release-bot@kestrelcom.example commit -q -m "Regenerate clients for $version"
fi
git push -q origin HEAD:main
SH
