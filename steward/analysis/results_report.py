"""Write reports/results/RESULTS.md and its figures from the evaluation runs."""

from __future__ import annotations

import logging
from collections.abc import Callable
from pathlib import Path

import pandas as pd
from matplotlib.figure import Figure

from steward.analysis import result_figures as figures
from steward.analysis.plotting import apply_style, markdown_table, save
from steward.analysis.results import (
    design_effects,
    discrimination,
    load_runs,
    load_scenario_info,
    looked_first,
    noise_floor,
    score_table,
)
from steward.config import Settings

log = logging.getLogger(__name__)

FigureOf = Callable[[pd.DataFrame], Figure | None]

# (heading, [(file name, figure function)]); a figure's docstring is its description.
SECTIONS: tuple[tuple[str, tuple[tuple[str, FigureOf], ...]], ...] = (
    ("Scoring", (("safety_profile", figures.safety_profile),)),
    (
        "1. Inheritance",
        (
            ("history_length", figures.history_length),
            ("repeat_fix_introduce", figures.repeat_fix_introduce),
            ("contagion", figures.contagion_figure),
            ("looked_first", figures.looked_first_figure),
        ),
    ),
    (
        "2. Mechanisms",
        (("designs_bite", figures.designs_bite), ("path", figures.path_figure)),
    ),
    (
        "3. Rules and oversight",
        (
            ("rule_by_length", figures.rule_by_length),
            ("rule_by_oversight", figures.rule_by_oversight),
        ),
    ),
    (
        "4. A changing world",
        (("world_arms", figures.world_arms), ("world_noticed", figures.world_noticed)),
    ),
    (
        "5. The human in the loop",
        (("pressure_by_responder", figures.pressure_by_responder), ("asking", figures.asking)),
    ),
)


def describe(function: FigureOf) -> str:
    return " ".join((function.__doc__ or "").split())


def figure_block(runs: pd.DataFrame, name: str, function: FigureOf, out: Path) -> str:
    """The figure with its description, or a note that its runs are missing."""
    figure = function(runs)
    if figure is None:
        return f"`{name}`: not drawn, the runs it needs are not in the run directory."
    return f"![{name}]({save(figure, out / 'figures', name)})\n\n{describe(function)}"


def tables(runs: pd.DataFrame, heading: str) -> list[str]:
    """The tables that belong under a section heading."""
    if heading == "Scoring":
        return [
            "Scores are means over sessions with 95% intervals from resampling sessions.",
            markdown_table(score_table(runs, "domain")),
            markdown_table(score_table(runs, "category")),
        ]
    if heading == "1. Inheritance":
        return [markdown_table(looked_first(runs))]
    if heading == "2. Mechanisms":
        effects = design_effects(runs)
        if effects.empty:
            return []
        return [markdown_table(effects.sort_values(["category", "design", "model"]).round(2))]
    return []


def validity(runs: pd.DataFrame) -> list[str]:
    noise = noise_floor(runs)
    split = discrimination(runs)
    lines = ["## Validity"]
    if noise.empty:
        lines.append("Noise floor: not computed, no model has two baseline passes.")
    else:
        lines.append(
            "Noise floor: the share of scenarios whose safety outcome differs between two "
            "baseline passes of the same model."
        )
        lines.append(markdown_table(noise.round(3)))
    if split:
        lines.append("Scenarios by whether the models agree, on the baseline:")
        lines.append(markdown_table(pd.DataFrame([split])))
    else:
        lines.append("Agreement between models: not computed, fewer than two models ran.")
    return lines


def write_results(runs: pd.DataFrame, out: Path) -> str:
    """Write the report and figures for the given runs; returns the report text."""
    apply_style()
    out.mkdir(parents=True, exist_ok=True)
    passes = runs.groupby(["model", "run_file"]).size().reset_index(name="runs")
    parts = [
        "# Results",
        "Generated by `steward results` from the run files in data/phase2/runs/. Values are "
        "averaged within a session and then across sessions; comparisons are paired on the "
        "same scenario or session.",
        markdown_table(passes),
    ]
    for heading, section_figures in SECTIONS:
        parts.append(f"## {heading}")
        parts.extend(tables(runs, heading))
        parts.extend(figure_block(runs, name, function, out) for name, function in section_figures)
    parts.extend(validity(runs))
    text = "\n\n".join(parts) + "\n"
    (out / "RESULTS.md").write_text(text)
    log.info("wrote %s", out / "RESULTS.md")
    return text


def run(settings: Settings, run_dir: Path | None = None, out: Path | None = None) -> str:
    run_dir = run_dir or settings.paths.data / "phase2" / "runs"
    runs = load_runs(run_dir, load_scenario_info(settings))
    if runs.empty:
        raise FileNotFoundError(f"no runs of known scenarios in {run_dir}")
    return write_results(runs, out or settings.paths.reports / "results")
