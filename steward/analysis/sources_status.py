"""reports/SOURCES_STATUS.md: one row per source in brief section 4."""

from __future__ import annotations

import pandas as pd

from steward.analysis.tables import markdown_table
from steward.config import Settings
from steward.schema import StageBResult
from steward.sources.registry import LOADERS, UNAVAILABLE
from steward.store import is_written, read_jsonl, read_meta, written_sources


def status_rows(settings: Settings) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for name, source in sorted(LOADERS.items()):
        count = (
            len(read_meta(settings.paths.normalized, name))
            if is_written(settings.paths.normalized, name)
            else 0
        )
        rows.append(
            {
                "source": name,
                "domain": source.info.domain,
                "status": "ingested" if count else "not ingested",
                "count ingested": count,
                "license": source.info.license or "not stated",
                "location": source.info.location,
                "notes": source.info.notes,
                "reason if unavailable": ""
                if count
                else "loader produced no trajectories; see data/logs",
                "unblock": "",
            }
        )
    for name, entry in sorted(UNAVAILABLE.items()):
        rows.append(
            {
                "source": name,
                "domain": entry.domain,
                "status": "unavailable",
                "count ingested": 0,
                "license": entry.license or "not stated",
                "location": entry.location,
                "notes": "",
                "reason if unavailable": entry.reason,
                "unblock": entry.unblock,
            }
        )
    return rows


def devops_row(settings: Settings) -> dict[str, object]:
    """Brief 4.2 lists DevOps sessions within the SWE sources as a source assigned by rule."""
    domains = {
        r.trajectory_id: r.domain
        for r in read_jsonl(settings.paths.stage_b / "results.jsonl", StageBResult)
    }
    counts: dict[str, int] = {}
    for source in written_sources(settings.paths.normalized):
        for meta in read_meta(settings.paths.normalized, source):
            if meta.real_user and domains.get(meta.trajectory_id, meta.domain) == "terminal_devops":
                counts[source] = counts.get(source, 0) + 1
    detail = ", ".join(f"{s}: {n}" for s, n in sorted(counts.items()))
    return {
        "source": "devops_sessions_in_swe_sources",
        "domain": "terminal_devops",
        "status": "ingested" if counts else "not ingested",
        "count ingested": sum(counts.values()),
        "license": "per parent source",
        "location": "derived from the real-user SWE sources",
        "notes": f"Assigned by the domain rule, or by Stage B where the rule was undecided ({detail})",
        "reason if unavailable": "",
        "unblock": "",
    }


def write_sources_status(settings: Settings) -> str:
    rows = status_rows(settings) + [devops_row(settings)]
    frame = pd.DataFrame(rows)
    ingested = frame[
        (frame.status == "ingested") & (frame.source != "devops_sessions_in_swe_sources")
    ]
    text = "\n".join(
        [
            "# Sources status",
            "",
            f"{len(ingested)} of {len(frame) - 1} downloadable sources are ingested, {int(ingested['count ingested'].sum()):,} "
            "trajectories in total; the DevOps row is a subset of the real-user sources. Domain is the source's default; mixed real-user sources are "
            "split by the domain rule in steward/sources/domain_rule.py. This file is generated by "
            "`steward sources-status`.",
            "",
            markdown_table(frame),
            "",
        ]
    )
    path = settings.paths.reports / "SOURCES_STATUS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return text
