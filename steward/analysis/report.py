"""Assemble reports/PHASE1_STATS.md and its figures from every section module."""

from __future__ import annotations

import logging

from steward.analysis.corpus_sections import (
    corpus_section,
    funnel_section,
    moments_section,
    real_users_section,
)
from steward.analysis.inputs import load, ranked_ids
from steward.analysis.plotting import apply_style
from steward.analysis.score_sections import (
    coverage_section,
    criteria_section,
    jump_in_section,
    limitations_section,
)
from steward.config import Settings

log = logging.getLogger(__name__)


def write_report(settings: Settings) -> str:
    apply_style()
    inputs = load(settings)
    figures = settings.paths.figures
    sections = [
        funnel_section(inputs, ranked_ids(settings), figures),
        corpus_section(inputs, figures),
        moments_section(inputs, figures),
        real_users_section(inputs, figures),
        criteria_section(inputs, figures),
        coverage_section(inputs, figures),
        jump_in_section(inputs, figures),
        limitations_section(inputs),
    ]
    text = (
        "\n\n".join(
            [
                "# Phase 1 statistics",
                "Generated by `steward analyze` from the stage outputs in data/, for swe, "
                "terminal_devops and workplace. This is the appendix to PHASE1.md; figures are in "
                "reports/figures/.",
                *sections,
            ]
        )
        + "\n"
    )
    path = settings.paths.reports / "PHASE1_STATS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    log.info("wrote %s", path)
    return text
