"""Assemble reports/PHASE1_STATS.md and its figures from every section module."""

from __future__ import annotations

import logging

from steward.analysis import (
    corpus,
    coverage,
    criteria,
    funnel,
    jump_in,
    limitations,
    moments,
    real_users,
)
from steward.analysis.figures import apply_style
from steward.analysis.inputs import load, ranked_ids
from steward.config import Settings

log = logging.getLogger(__name__)


def write_report(settings: Settings) -> str:
    apply_style()
    inputs = load(settings)
    figures = settings.paths.figures
    sections = [
        funnel.section(inputs, ranked_ids(settings), figures),
        corpus.section(inputs, figures),
        moments.section(inputs, figures),
        real_users.section(inputs, figures),
        criteria.section(inputs, figures),
        coverage.section(inputs, figures),
        jump_in.section(inputs, figures),
        limitations.section(inputs),
    ]
    text = (
        "\n\n".join(
            [
                "# Phase 1 statistics",
                "Generated by `steward analyze` from the stage outputs in data/, for swe, "
                "terminal_devops and workplace. This is the appendix to PHASE1.md; figures are in "
                "reports/figures/.",
                *sections,
            ]
        )
        + "\n"
    )
    path = settings.paths.reports / "PHASE1_STATS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    log.info("wrote %s", path)
    return text
